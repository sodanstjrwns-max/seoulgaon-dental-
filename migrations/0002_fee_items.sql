-- 비급여 수가표 (fee schedule) — 원장 편집 + 항목별 공개/비공개 토글
-- 공개 페이지: /guide (#fee) 에 is_published=1 항목만 노출.
-- 앱(src/index.tsx)의 ensureFees()가 테이블 미존재/빈 상태를 자가 복구·시드하지만,
-- 프로덕션 D1 결정성을 위해 이 마이그레이션으로 생성+시드한다.
CREATE TABLE IF NOT EXISTS fee_items (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  category TEXT NOT NULL DEFAULT '기타',
  name TEXT NOT NULL,
  price TEXT NOT NULL DEFAULT '',
  note TEXT NOT NULL DEFAULT '',
  is_nhi INTEGER NOT NULL DEFAULT 0,
  is_published INTEGER NOT NULL DEFAULT 1,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_fee_pub ON fee_items(is_published, sort_order);

